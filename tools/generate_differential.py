"""Generate owned fixtures using edn_format 0.7.5 as an independent oracle.

No upstream fixtures or source code are copied. Only the shared, documented
EDN subset is compared: no Clojure extensions, unknown tags or duplicate keys.
Run with --check to verify the committed fixture without modifying the tree.
"""
import argparse
import subprocess
import tempfile
import shutil
import decimal
import importlib.metadata
import json
import pathlib
import random
import uuid
from collections.abc import Mapping
import edn_format as edn
from edn_format.immutable_list import ImmutableList


def quoted(text):
    return json.dumps(text, ensure_ascii=False)


def moon(value):
    if value is None:
        return 'Nil'
    if isinstance(value, bool):
        return 'Bool(' + str(value).lower() + ')'
    if isinstance(value, int):
        return 'Integer(' + quoted(str(value)) + ')'
    if isinstance(value, float):
        return 'Float(' + repr(value) + ')'
    if isinstance(value, decimal.Decimal):
        return 'Decimal(' + quoted(str(value)) + ')'
    if isinstance(value, edn.Keyword):
        return 'Keyword(' + quoted(value.name) + ')'
    if isinstance(value, edn.Symbol):
        return 'Symbol(' + quoted(value.name) + ')'
    if isinstance(value, str):
        return 'Text(' + quoted(value) + ')'
    if isinstance(value, ImmutableList):
        return 'Vector([' + ','.join(map(moon, value)) + '])'
    if isinstance(value, tuple):
        return 'List([' + ','.join(map(moon, value)) + '])'
    if isinstance(value, frozenset):
        return 'Set([' + ','.join(sorted(map(moon, value))) + '])'
    if isinstance(value, Mapping):
        return 'Mapping([' + ','.join('(' + moon(k) + ',' + moon(v) + ')' for k, v in value.items()) + '])'
    if isinstance(value, uuid.UUID):
        return 'Tagged("uuid",Text(' + quoted(str(value)) + '))'
    raise TypeError(type(value))


def corpus():
    rng = random.Random(20261109)
    atoms = ['nil', 'true', 'false', '42', '-7', '0.125', '12.50M', ':db/id', 'app/name', '"hello"', '"line\\nnext"', '"中文🙂"']

    def tree(depth):
        if depth == 0 or rng.randrange(4) == 0:
            return rng.choice(atoms)
        count = rng.randrange(4)
        kind = rng.randrange(3)
        if kind == 2:
            return '{' + ' '.join(':k' + str(i) + ' ' + tree(depth - 1) for i in range(count)) + '}'
        op, cl = ('[', ']') if kind == 0 else ('(', ')')
        return op + ' '.join(tree(depth - 1) for _ in range(count)) + cl

    cases = atoms + ['{}', '#{}', '()', '[]', '#{a b 1}', '{[1 2] (a b) (3 4) [true nil]}', '[a #_discarded b]', '#uuid "f81d4fae-7dec-11d0-a765-00a0c91e6bf6"']
    cases.extend(tree(4) for _ in range(180))
    return cases


def generate():
    if importlib.metadata.version('edn_format') != '0.7.5':
        raise RuntimeError('oracle version must be 0.7.5')
    lines = ['// Generated by tools/generate_differential.py; fixture code is not production LOC.', '///|', 'test "independent edn_format 0.7.5 differential corpus" {']
    for index, source in enumerate(corpus()):
        expected = moon(edn.loads(source))
        lines.append('  {')
        lines.append('    let actual = read(' + quoted(source) + ')')
        lines.append('    let expected : Value = ' + expected)
        lines.append('    assert_true(equivalent(actual, expected), msg="oracle case ' + str(index) + '")')
        lines.append('    assert_eq(write(actual,canonical=true),write(expected,canonical=true))')
        lines.append('  }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    config = args.parse_args()
    target = pathlib.Path(__file__).resolve().parents[1] / 'differential_wbtest.mbt'
    generated = generate()
    formatter = shutil.which('moon')
    if formatter is None:
        raise RuntimeError('moon must be on PATH to normalize generated Moon source')
    with tempfile.TemporaryDirectory(prefix='moonedn-oracle-') as tmp:
        folder = pathlib.Path(tmp)
        (folder / 'moon.mod').write_text('name = "fixture/oracle"\n', encoding='utf-8')
        (folder / 'moon.pkg').write_text('', encoding='utf-8')
        fixture = folder / 'differential_wbtest.mbt'
        fixture.write_text(generated, encoding='utf-8')
        subprocess.run([formatter, 'fmt'], cwd=folder, check=True, capture_output=True)
        generated = fixture.read_text(encoding='utf-8')
    if config.check:
        if target.read_text(encoding='utf-8') != generated:
            raise SystemExit('differential fixture differs; regenerate then run moon fmt')
    else:
        target.write_text(generated, encoding='utf-8')
    print(str(len(corpus())) + ' independent reference cases verified')


if __name__ == '__main__':
    main()
